//Write a C program to create predefined values length = 15 and width = 10, and calculate the area of a rectangle.
#include <stdio.h>
int main()
{
    int length = 15;  // Predefined value
    int width = 10;  // Predefined value
    int area = length * width;  // Calculate area
    printf("The area of the rectangle with length %d and width %d is: %d\n", length, width, area);
    return 0;
}