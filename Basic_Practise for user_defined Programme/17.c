//Write a C program with a predefined value side = 8 and calculate the perimeter of a square.
#include <stdio.h>
int main()  
{
    int side = 8;  // Predefined value
    int perimeter = 4 * side;  // Calculate perimeter
    printf("The perimeter of the square with side %d is: %d\n", side, perimeter);
    return 0;
}