//Write a C program to create two variables with predefined values and print their sum
#include <stdio.h>
int main()
{
    int a = 10;  // Predefined value
    int b = 20;  // Predefined value
    int sum = a + b;  // Calculate sum
    printf("The sum of %d and %d is: %d\n", a, b, sum);
    return 0;
}