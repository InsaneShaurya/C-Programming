//Write a C program to create predefined values for length = 10 and breadth = 5, and calculate the area of a rectangle.
#include <stdio.h>
int main() 
{
    int length = 10;  // Predefined value
    int breadth = 5;  // Predefined value
    int area = length * breadth;  // Calculate area
    printf("The area of the rectangle with length %d and breadth %d is: %d\n", length, breadth, area);
    return 0;
}